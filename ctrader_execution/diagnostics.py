def safe_capability_code(exc):
    if isinstance(exc,KeyboardInterrupt):return 'OWNER_INTERRUPTED'
    if isinstance(exc,BlockingIOError):return 'ACCOUNT_EXECUTION_OWNER_BUSY'
    if isinstance(exc,PermissionError):return 'PRIVATE_FILE_ACCESS_DENIED'
    if isinstance(exc,FileNotFoundError):return 'PRIVATE_FILE_MISSING'
    return str(exc) if isinstance(exc,SafetyError) and str(exc) in CODES else 'CAPABILITY_VALIDATION_FAILED'
